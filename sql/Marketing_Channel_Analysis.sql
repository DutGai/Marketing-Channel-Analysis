# 9. Compare campaign acceptance and customer spending
WITH customer_analysis AS (

    SELECT
        ID,
        Response,

        (
            MntWines +
            MntFruits +
            MntMeatProducts +
            MntFishProducts +
            MntSweetProducts +
            MntGoldProds
        ) AS Total_Spending

    FROM marketing

),

campaign_summary AS (

    SELECT
        Response,

        COUNT(*) AS Total_Customers,

        SUM(Total_Spending) AS Total_Revenue,

        AVG(Total_Spending) AS Average_Spending

    FROM customer_analysis

    GROUP BY Response

)

SELECT
    Response,
    Total_Customers,
    Total_Revenue,

    ROUND(Average_Spending, 2) AS Average_Spending

FROM campaign_summary;

-- Findings: The analysis of 2,216 customers revealed a 14.91% campaign response rate, 
-- with responders spending an average of 985.66 compared to 540.12 for non-responders, 
-- suggesting that campaign responders are a more valuable customer segment.

# 10. Which customers should the marketing team target?
SELECT
    ID,

    Income,

    (
        MntWines +
        MntFruits +
        MntMeatProducts +
        MntFishProducts +
        MntSweetProducts +
        MntGoldProds
    ) AS Total_Spending,

    CASE

        WHEN (
            MntWines + MntFruits +
            MntMeatProducts + MntFishProducts +
            MntSweetProducts + MntGoldProds
        ) >= 1500
        THEN 'High Value Customer'

        WHEN (
            MntWines + MntFruits +
            MntMeatProducts + MntFishProducts +
            MntSweetProducts + MntGoldProds
        ) >= 500
        THEN 'Medium Value Customer'

        ELSE 'Low Value Customer'

    END AS Customer_Category

FROM marketing

ORDER BY Total_Spending DESC;

-- Finding: This allows the marketing team to identify high-value customers,
--  for targeted campaigns and customer retention activities. 

# 10. Calculate CAC by campaign response
SELECT
    Response,
    COUNT(*) AS Total_Customers,
    SUM(Z_CostContact) AS Contact_Cost,
    SUM(Response * Z_Revenue) AS Response_Revenue,

    COALESCE(
        ROUND(SUM(Z_CostContact) / NULLIF(SUM(Response), 0), 2),
        0
    ) AS CAC,

    COALESCE(
        ROUND(SUM(Response * Z_Revenue) / NULLIF(SUM(Z_CostContact), 0), 2),
        0
    ) AS ROAS

FROM marketing
GROUP BY Response;

-- Findings: For those who responded , their response_revenue was 3663 per customer ,
-- CAC is 3.00 per customer and ROAS is 3.67 per customer ,
-- and to those who did not responded their CAC and ROAS was not recorded .

